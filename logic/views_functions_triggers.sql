-- Purpose: Views, function, and membership audit trigger.

-- View 1: Active club members.
CREATE OR REPLACE VIEW active_club_members AS
SELECT s.student_id,
       s.first_name,
       s.last_name,
       s.email,
       c.club_id,
       c.club_name,
       m.join_date,
       m.membership_role,
       m.status
FROM student s
JOIN membership m ON s.student_id = m.student_id
JOIN club c ON m.club_id = c.club_id
WHERE LOWER(m.status) = 'active';

-- View 2: Attendance summary for each event.
CREATE OR REPLACE VIEW event_attendance_summary AS
SELECT e.event_id,
       e.event_name,
       e.event_date,
       c.club_name,
       COUNT(a.attendance_id) AS attendance_count
FROM event e
JOIN club c ON e.club_id = c.club_id
LEFT JOIN attendance a ON e.event_id = a.event_id
GROUP BY e.event_id, e.event_name, e.event_date, c.club_name;

-- Audit table: Records membership inserts, updates, and deletes.
CREATE TABLE IF NOT EXISTS membership_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membership_id INTEGER,
    action_type VARCHAR(10) NOT NULL,
    old_data JSONB,
    new_data JSONB,
    changed_by TEXT NOT NULL DEFAULT CURRENT_USER,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Trigger function: Save the previous and/or new membership record.
CREATE OR REPLACE FUNCTION audit_membership_changes()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO membership_audit
            (membership_id, action_type, new_data)
        VALUES
            (NEW.membership_id, TG_OP, TO_JSONB(NEW));
        RETURN NEW;

    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO membership_audit
            (membership_id, action_type, old_data, new_data)
        VALUES
            (NEW.membership_id, TG_OP, TO_JSONB(OLD), TO_JSONB(NEW));
        RETURN NEW;

    ELSIF TG_OP = 'DELETE' THEN
        INSERT INTO membership_audit
            (membership_id, action_type, old_data)
        VALUES
            (OLD.membership_id, TG_OP, TO_JSONB(OLD));
        RETURN OLD;
    END IF;

    RETURN NULL;
END;
$$;

-- Recreate the trigger safely when rerunning this script.
DROP TRIGGER IF EXISTS membership_audit_trigger ON membership;

CREATE TRIGGER membership_audit_trigger
AFTER INSERT OR UPDATE OR DELETE ON membership
FOR EACH ROW
EXECUTE FUNCTION audit_membership_changes();
